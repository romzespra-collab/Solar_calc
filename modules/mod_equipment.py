def _mppt(v_max, vmpp_min, vmpp_max, iin_max, iout_max, eta=97, eta_k=0, own_w=0, headroom=0, pv_pmax=0, n_mppt_max=1):
    return dict(v_max=v_max, vmpp_min=vmpp_min, vmpp_max=vmpp_max, iin_max=iin_max, iout_max=iout_max, eta=eta,
                eta_k=eta_k, own_w=own_w, headroom=headroom, pv_pmax=pv_pmax, n_mppt_max=n_mppt_max)


def _inv(inv_p, inv_eta, inv_idle, bat_v=0, mppt=None):
    d = dict(inv_p=inv_p, inv_eta=inv_eta, inv_idle=inv_idle, inv_bat_v=bat_v)
    if mppt:
        d["mppt"] = mppt
    return d


